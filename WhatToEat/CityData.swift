    // MARK: - 搜索城市
    static func searchCities(query: String) -> [String] {
        let lowerQuery = query.lowercased().trimmingCharacters(in: .whitespaces)
        guard !lowerQuery.isEmpty else { return [] }
        
        return allCities.filter { city in
            // 1. 名称包含匹配
            city.contains(query) ||
            // 2. 拼音全拼匹配
            pinyinMap[city]?.contains(lowerQuery) ?? false ||
            // 3. 拼音首字母匹配
            getPinyinInitial(city).contains(lowerQuery)
        }
    }
    
    // MARK: - 获取拼音首字母
    private static func getPinyinInitial(_ city: String) -> String {
        guard let pinyin = pinyinMap[city] else { return "" }
        return String(pinyin.prefix(1))
    }
    
    // MARK: - 获取完整拼音
    static func getPinyin(_ city: String) -> String {
        return pinyinMap[city] ?? ""
    }
    
    // MARK: - 检查城市是否存在
    static func isValidCity(_ city: String) -> Bool {
        return allCities.contains(city)
    }
    
    // MARK: - 获取城市列表（热门城市在前）
    static func getCities() -> [String] {
        // 热门城市 + 其他城市（去重）
        var result = hotCities
        let otherCities = allCities.filter { !hotCities.contains($0) }
        result.append(contentsOf: otherCities)
        return result
    }
